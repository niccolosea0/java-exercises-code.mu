// Task N2 Write a program that will find out how many seconds are in a day.

public class Seconds {
    public static void main(String[] args) {

        int hoursInDay = 24;
        int minutesInDay = hoursInDay * 60;
        int secondsInDay = minutesInDay * 60;

        System.out.println("There is " + secondsInDay + " seconds in a day!");
    }
}
